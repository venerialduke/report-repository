// Report viewer: framed report + metadata rail + actions (select, AI, PDF, share) + comments.
import { $, esc, icon, mountChrome, loadCatalog, fmtDate, selection, toast, avatarColor, initials, areaColor, areaURL, relDate } from "./core.js";
import { mountComments } from "./comments.js";

const id = new URLSearchParams(location.search).get("id");
const SOURCE_LABEL = { "google-docs": "Google Doc", "google-slides": "Google Slides", word: "Word document", powerpoint: "PowerPoint", notebook: "Notebook", other: "Source document" };

async function main() {
  const cfg = await mountChrome("report");
  const cat = await loadCatalog();
  const r = cat.reports.find((x) => x.id === id);
  if (!r) {
    $("#main").innerHTML = `<div class="empty" style="margin-top:48px"><h2>Report not found</h2><p>No report with id <code>${esc(id)}</code>. It may have been renamed or removed.</p><a class="btn primary" href="./">Back to the hub</a></div>`;
    return;
  }
  document.title = `${r.title} — ${cfg.siteName}`;
  $("#crumbs").innerHTML = `<a href="./">Insights Hub</a><span>/</span><a href="${areaURL(cat, r.area)}">${esc(r.area)}</a><span>/</span><span class="cur" title="${esc(r.title)}">${esc(r.title)}</span>`;

  // ---------- actions ----------
  const actions = $("#actions");
  actions.innerHTML = `
    <button class="btn sm" id="act-select" aria-pressed="${selection.has(r.id)}"></button>
    <button class="btn sm primary" id="act-ai">${icon("sparkle")}AI summary</button>
    <button class="btn sm" id="act-pdf">${icon("pdf")}PDF</button>
    <button class="btn sm" id="act-share" title="Copy link">${icon("link")}Share</button>
    <a class="btn sm ghost icon" href="${esc(r.url)}" target="_blank" rel="noopener" title="Open standalone" aria-label="Open standalone">${icon("ext")}</a>`;
  const selBtn = $("#act-select");
  const paintSel = () => {
    const on = selection.has(r.id);
    selBtn.setAttribute("aria-pressed", on);
    selBtn.innerHTML = on ? `${icon("check")}Selected` : `${icon("plus")}Select`;
    selBtn.title = on ? "Remove from selection" : "Add to selection (for multi-report AI summary or PDF bundle)";
  };
  paintSel();
  window.addEventListener("selection-change", paintSel);
  selBtn.addEventListener("click", () => { selection.toggle(r.id); });
  $("#act-ai").addEventListener("click", async () => (await import("./ai.js")).openAI([r.id]));
  $("#act-pdf").addEventListener("click", () => {
    const w = frame.contentWindow;
    try { w.focus(); w.print(); } catch { window.open(r.url, "_blank"); }
  });
  $("#act-share").addEventListener("click", async () => {
    try { await navigator.clipboard.writeText(location.href); toast("Link copied"); } catch { prompt("Copy this link:", location.href); }
  });

  // ---------- frame ----------
  const frame = $("#frame");
  frame.title = r.title;
  frame.src = r.url;
  frame.addEventListener("load", () => {
    let doc;
    try { doc = frame.contentDocument; } catch { return; }
    if (!doc) return;
    doc.documentElement.classList.add("pp-embedded");
    const fit = () => { frame.style.height = doc.documentElement.scrollHeight + "px"; };
    fit();
    new ResizeObserver(fit).observe(doc.body);
    setTimeout(fit, 400);
    // Keep navigation inside the hub: links to other reports open in the viewer, external links in a new tab
    doc.addEventListener("click", (e) => {
      const a = e.target.closest("a[href]");
      if (!a || a.getAttribute("href").startsWith("#")) return;
      const url = new URL(a.href, doc.baseURI);
      const m = url.pathname.match(/\/reports\/([a-z0-9-]+)\/?(index\.html)?$/);
      e.preventDefault();
      if (url.origin === location.origin && m) location.href = `report.html?id=${m[1]}`;
      else window.open(url.href, "_blank", "noopener");
    });
  });

  renderRail(r, cat, cfg);
  mountComments($("#comments"), r, cfg);
}

function renderRail(r, cat, cfg) {
  const statusBadge = { final: "Final", draft: "Draft — for review", superseded: "Superseded" }[r.status] || r.status;
  const codeURL = (p) => (/^https?:/.test(p) ? p : (cfg.teamRepo || "") + p);
  const related = (r.related || []).map((id) => cat.reports.find((x) => x.id === id)).filter(Boolean);
  const aiSummary = r.ai_summary
    ? `<div class="ai-sum">${r.ai_summary.split(/\n{2,}/).map((p) => `<p>${esc(p)}</p>`).join("")}<p style="font-size:12px;color:var(--text-3)">Generated by Claude from the report text. Check anything important against the report.</p></div>`
    : `<p class="ai-sum" style="margin:0 0 10px">Get a short summary, an exec brief, or ask a question about this report.</p>`;

  $("#rail").innerHTML = `
    <section class="panel" style="border-top:4px solid ${areaColor(cat, r.area)}">
      <h3>About <span class="pill ${r.status === "final" ? "" : esc(r.status)}">${esc(statusBadge)}</span></h3>
      <dl>
        <dt>Area</dt><dd><a href="${areaURL(cat, r.area)}">${esc(r.area)}</a></dd>
        <dt>Type</dt><dd>${r.type === "article" ? "Article" : "Report"}</dd>
        <dt>Published</dt><dd>${fmtDate(r.published)}</dd>
        ${r.updated && r.updated !== r.published ? `<dt>Updated</dt><dd>${fmtDate(r.updated)} <span style="color:var(--text-3)">(${relDate(r.updated)})</span></dd>` : ""}
        <dt>Length</dt><dd>${r.reading_minutes} min read · ${r.charts} chart${r.charts === 1 ? "" : "s"}</dd>
      </dl>
    </section>

    <section class="panel">
      <h3>Owners</h3>
      ${(r.owners || []).map((o) => `<div class="owner"><span class="avatar" style="background:${avatarColor(o.name)}">${esc(initials(o.name))}</span>
        <div><a href="./?owner=${encodeURIComponent(o.name)}">${esc(o.name)}</a><div class="role">${esc(o.role || "")}${o.email ? ` · <a href="mailto:${esc(o.email)}?subject=${encodeURIComponent("Re: " + r.title)}">Email</a>` : ""}</div></div></div>`).join("")}
    </section>

    ${r.key_findings?.length ? `<section class="panel"><h3>Key findings</h3><ol class="findings">${r.key_findings.map((f) => `<li>${esc(f)}</li>`).join("")}</ol></section>` : ""}

    <section class="panel">
      <h3>AI summary ${r.ai_summary ? '<span class="pill">Pre-generated</span>' : ""}</h3>
      ${aiSummary}
      <button class="btn sm" id="rail-ai">${icon("sparkle")}${r.ai_summary ? "More AI options" : "Summarise with AI"}</button>
    </section>

    <section class="panel">
      <h3>Topics & tags</h3>
      <div style="display:flex;flex-wrap:wrap;gap:6px">
        ${(r.topics || []).map((t) => `<a class="chip" href="./?topic=${encodeURIComponent(t)}">${esc(t)}</a>`).join("")}
        ${(r.tags || []).map((t) => `<a class="chip" href="./?tag=${encodeURIComponent(t)}">#${esc(t)}</a>`).join("")}
      </div>
    </section>

    ${r.code?.length ? `<section class="panel"><h3>Code</h3><ul class="linklist">${r.code.map((c) => `<li><a href="${esc(codeURL(c.path))}" target="_blank" rel="noopener">${icon("code")}<span style="min-width:0">${esc(c.label)}<span class="p">${esc(c.path)}</span></span></a></li>`).join("")}</ul></section>` : ""}

    ${r.source ? `<section class="panel"><h3>Original document</h3><ul class="linklist"><li>${r.source.url
      ? `<a href="${esc(r.source.url)}" target="_blank" rel="noopener">${icon("file")}<span style="min-width:0">${esc(r.source.title || SOURCE_LABEL[r.source.type] || "Source")}<span class="p">${esc(SOURCE_LABEL[r.source.type] || r.source.type)}${r.source.imported ? ` · imported ${fmtDate(r.source.imported)}` : ""}</span></span></a>`
      : `<span style="display:flex;gap:8px;padding:4px 0;font-size:13.5px">${icon("file")}<span>${esc(SOURCE_LABEL[r.source.type] || r.source.type)}${r.source.imported ? ` · imported ${fmtDate(r.source.imported)}` : ""}</span></span>`}</li></ul></section>` : ""}

    ${r.data_sources?.length ? `<section class="panel"><h3>Data sources</h3><ul class="linklist">${r.data_sources.map((d) => `<li><span style="display:flex;gap:8px;padding:4px 0;font-size:13.5px">${icon("db")}<span>${esc(d)}</span></span></li>`).join("")}</ul></section>` : ""}

    ${related.length ? `<section class="panel"><h3>Related</h3>${related.map((x) => `<a class="related-card" href="report.html?id=${encodeURIComponent(x.id)}"><small>${esc(x.area)} · ${fmtDate(x.published)}</small>${esc(x.title)}</a>`).join("")}</section>` : ""}
  `;
  $("#rail-ai").addEventListener("click", async () => (await import("./ai.js")).openAI([r.id]));
}

main();
